// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks pre-token protocols by an implied launch value that follows only
// from the snapshot's own figures. Nothing is hard-coded by name: the same function
// scores every protocol, and the multiples it uses are calibrated from the snapshot
// itself, from the protocols in it whose token already trades.
//
//   multiple   = the category's median mcap/TVL among this snapshot's token-traded
//                protocols (at least 3 of them; otherwise the global median), clamped
//                to [0.05, 1.50]. A DEX is worth what DEX tokens trade for, not what a
//                lending token trades for, and the snapshot says what that is.
//   growth     = change_7d clamped to [-50, +100] per cent
//   growthMult = 1 + (growth / 100) * 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 * 0.4   (age unknown: 365 days)
//   breadth    = 1 + 0.015 * min(max(chains - 1, 0), 10)  (more chains, more surface)
//   implied    = max(1, round(tvl_usd * multiple * growthMult * maturityMult * breadth))
//
// The board covers every slug on the snapshot's watchlist (the floor, never a
// ceiling) plus the strongest pre-token protocols below the floor, by implied value.
// Protocols whose token already trades are kept apart and shown as the market's own
// values, never mixed into the ranked board: they are the calibration set and the
// dashboard's Live view, not farm targets.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

